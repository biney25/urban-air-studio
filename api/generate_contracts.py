"""Generate OpenAPI and TypeScript definitions from real FastAPI/Pydantic contracts."""
import json
from pathlib import Path
from api.main import app


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1].replace("-","_")
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    variants = schema.get("anyOf") or schema.get("oneOf")
    if variants:
        return " | ".join(typescript(item) for item in variants)
    kind = schema.get("type")
    if kind == "array":
        return "Array<"+typescript(schema.get("items",{}))+">"
    if kind in {"number","integer"}:
        return "number"
    if kind == "string":
        return "string"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "object" or "properties" in schema:
        required = set(schema.get("required",[]))
        properties = [json.dumps(key)+(":" if key in required else "?:")+" "+typescript(value)+";"
                      for key,value in schema.get("properties",{}).items()]
        if schema.get("additionalProperties") is True or not properties:
            properties.append("[key: string]: unknown;")
        return "{ "+" ".join(properties)+" }"
    return "unknown"


def main():
    root = Path(__file__).resolve().parents[1]
    destination = root / "contracts"
    destination.mkdir(exist_ok=True)
    schema = app.openapi()
    (destination/"openapi.json").write_text(json.dumps(schema,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    definitions = ["// Generated by python -m api.generate_contracts; do not edit."]
    for name,value in schema["components"]["schemas"].items():
        definitions.append("export type "+name.replace("-","_")+" = "+typescript(value)+";")
    (destination/"api-types.ts").write_text("\n\n".join(definitions)+"\n",encoding="utf-8")
    print(f"Generated {len(schema['components']['schemas'])} schemas")


if __name__ == "__main__":
    main()
